// Generate procedural fallback textures so the app works reliably offline/instantaneously
let cachedLiving = '';
let cachedKitchen = '';
let cachedBedroom = '';
let cachedTerrace = '';

export function getProceduralPano(type: 'living' | 'kitchen' | 'bedroom' | 'terrace'): string {
  if (typeof window === 'undefined') return '';
  if (type === 'living') {
    if (!cachedLiving) cachedLiving = generateEquirectangularPanorama('living');
    return cachedLiving;
  }
  if (type === 'kitchen') {
    if (!cachedKitchen) cachedKitchen = generateEquirectangularPanorama('kitchen');
    return cachedKitchen;
  }
  if (type === 'bedroom') {
    if (!cachedBedroom) cachedBedroom = generateEquirectangularPanorama('bedroom');
    return cachedBedroom;
  }
  if (type === 'terrace') {
    if (!cachedTerrace) cachedTerrace = generateEquirectangularPanorama('terrace');
    return cachedTerrace;
  }
  return '';
}

